#!/usr/bin/env python3
"""Regenerate data.js for Epic 26 web reader from Draft 15 chapter files.

Source: /workspace/epic26/d15/ch/c01.txt … c13.txt
Each source line is LINE_NUMBER|text — the leading N| is stripped.
Blank lines and '* * *' scene breaks are preserved as paragraphs.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CH_DIR = Path("/workspace/epic26/d15/ch")
OUT = ROOT / "data.js"

LINE_RE = re.compile(r"^(\d+)\|(.*)$")

# Locked 25 Oct 2026. One A2 file per chapter, relative to the reader root.
# Chapters 03, 04, and 11 use storyboard panels: no dedicated plate
# (11 keeps a unique field beat; the counterfeit plate stays on 06).
CHAPTER_IMAGES = {
    "01": "plates/01_dust_on_the_road_a2.jpg",
    "02": "plates/02_sky_that_broke_a2.jpg",
    "03": "plates/sb3_panel_06_a2.jpg",
    "04": "plates/sb3_panel_07_a2.jpg",
    "05": "plates/03_parasitic_cycle_a2.jpg",
    "06": "plates/09_counterfeit_flame_a2.jpg",
    "07": "plates/04_beast_black_cave_a2.jpg",
    "08": "plates/04_beast_black_cave_paradym_a2.jpg",
    "09": "plates/05_mammoth_on_the_ranch_a2.jpg",
    "10": "plates/06_buried_flame_a2.jpg",
    "11": "plates/sb3_panel_23_a2.jpg",
    "12": "plates/07_we_remember_a2.jpg",
    "13": "plates/08_the_margin_a2.jpg",
}


def strip_line(raw: str) -> str:
    m = LINE_RE.match(raw)
    if m:
        return m.group(2)
    # Already plain text (no prefix)
    return raw


def parse_chapter(path: Path, chap_id: str) -> dict:
    raw_lines = path.read_text(encoding="utf-8").splitlines()
    texts = [strip_line(L) for L in raw_lines]

    if not texts:
        raise SystemExit(f"empty chapter file: {path}")

    # First non-empty line = chapter label (e.g. "Chapter One" or "Acknowledgments")
    # Second non-empty (if present and not body-looking) = title for numbered chapters
    i = 0
    while i < len(texts) and texts[i].strip() == "":
        i += 1
    if i >= len(texts):
        raise SystemExit(f"no content in {path}")

    label = texts[i].strip()
    i += 1

    title = ""
    # Numbered chapters: next non-empty line is the title
    if re.match(r"^Chapter\s+", label, re.I):
        while i < len(texts) and texts[i].strip() == "":
            i += 1
        if i < len(texts):
            title = texts[i].strip()
            i += 1
    elif label.lower() == "acknowledgments":
        # Acknowledgments has no separate title line
        title = ""
    else:
        # Fallback: treat first line as title, label as chapter id
        title = label
        label = f"Chapter {chap_id.lstrip('0') or '0'}"

    paragraphs = texts[i:]  # keep blanks and * * *

    chapter = {
        "id": chap_id,
        "number": label,
        "title": title,
    }
    image = CHAPTER_IMAGES.get(chap_id)
    if image:
        chapter["image"] = image
    chapter["paragraphs"] = paragraphs
    return chapter


def main() -> None:
    chapters = []
    for n in range(1, 14):
        cid = f"{n:02d}"
        path = CH_DIR / f"c{cid}.txt"
        if not path.exists():
            raise SystemExit(f"missing chapter: {path}")
        chapters.append(parse_chapter(path, cid))

    book = {
        "title": "Epic 26",
        "subtitle": "The Traveler's Codex",
        "chapters": chapters,
    }

    # Compact-ish but readable JSON for debugging; UTF-8 preserved
    payload = json.dumps(book, ensure_ascii=False, indent=2)
    OUT.write_text(
        "// Generated by tools/build_data.py — do not edit by hand.\n"
        "// Source: /workspace/epic26/d15/ch/c01.txt … c13.txt (Novel Draft 15)\n"
        "window.BOOK = " + payload + ";\n",
        encoding="utf-8",
    )

    print(f"Wrote {OUT} ({OUT.stat().st_size} bytes)")
    for ch in chapters:
        body = [p for p in ch["paragraphs"] if p.strip()]
        print(
            f"  c{ch['id']}: {ch['number']}"
            + (f" — {ch['title']}" if ch["title"] else "")
            + f"  ({len(body)} body paras, {len(ch['paragraphs'])} total slots)"
        )


if __name__ == "__main__":
    main()
